"""Generate the faecal egg count data set for the two-drench goat trial.

Standard library only. Fixed seed so the file can be regenerated byte-for-byte.

Design
------
20 yearling dairy goats from one herd, randomised individually to one of two
drenches (10 per group). One faecal sample per goat 14 days after treatment,
each sample counted three times on three McMaster slides by the same
technician. 20 goats x 3 slides = 60 rows.

Counts are reported on the usual McMaster counting factor of 25 eggs per gram,
so every egg count in the file is a whole multiple of 25.
"""

import csv
import os
import random

SEED = 20260822
COUNTING_FACTOR = 25          # eggs per gram represented by one counted egg
N_PER_GROUP = 10
N_SLIDES = 3

GROUPS = (
    # label, post-treatment goat-level range (epg), slide noise as fraction
    ("benzimidazole", 160.0, 690.0),
    ("macrocyclic_lactone", 30.0, 245.0),
)

SLIDE_NOISE_FRACTION = 0.08   # small next to the between-goat spread
PRE_LOW, PRE_HIGH = 800.0, 2500.0


def to_counting_factor(value):
    """Round an egg count to the nearest whole multiple of the counting factor."""
    stepped = int(round(value / COUNTING_FACTOR)) * COUNTING_FACTOR
    return max(stepped, COUNTING_FACTOR)


def main():
    rng = random.Random(SEED)

    # Ear tags: year-of-birth prefix plus a within-year animal number, the way
    # a herd numbers its 2025-born replacements.
    tag_numbers = rng.sample(range(1, 400), N_PER_GROUP * len(GROUPS))
    tag_numbers.sort()
    tags = ["25-%03d" % n for n in tag_numbers]

    # Randomise individual goats to the two drenches.
    assignment = tags[:]
    rng.shuffle(assignment)
    allocation = {
        GROUPS[0][0]: sorted(assignment[:N_PER_GROUP]),
        GROUPS[1][0]: sorted(assignment[N_PER_GROUP:]),
    }

    rows = []
    for group_label, post_low, post_high in GROUPS:
        for tag in allocation[group_label]:
            pre = to_counting_factor(rng.uniform(PRE_LOW, PRE_HIGH))
            goat_true_post = rng.uniform(post_low, post_high)
            noise_sd = max(10.0, SLIDE_NOISE_FRACTION * goat_true_post)
            for slide in range(1, N_SLIDES + 1):
                post = to_counting_factor(rng.gauss(goat_true_post, noise_sd))
                rows.append([tag, group_label, slide, pre, post])

    here = os.path.dirname(os.path.abspath(__file__))
    out_path = os.path.join(here, "faecal_egg_counts.csv")
    with open(out_path, "w", newline="") as handle:
        writer = csv.writer(handle)
        writer.writerow(
            [
                "goat_tag",
                "drench_group",
                "slide_replicate",
                "pre_treatment_epg",
                "post_treatment_epg",
            ]
        )
        writer.writerows(rows)

    print("wrote %s (%d data rows)" % (out_path, len(rows)))


if __name__ == "__main__":
    main()
