"""Transit detection yield in planned TESS candidate light curves.

Reads inputs/data.csv, applies the prespecified photometric screening rule,
counts confirmed transit detections among the retained curves, and writes
results/report.md. The selected rate uses the retained post-screening subset
as its exposure denominator.
"""

import csv
from decimal import Decimal, ROUND_HALF_EVEN
from pathlib import Path

MAX_BASELINE_RMS_PPM = 1500

ROOT = Path(__file__).resolve().parent.parent
DATA_PATH = ROOT / "inputs" / "data.csv"
REPORT_PATH = ROOT / "results" / "report.md"


def load_rows(path):
    with path.open(newline="", encoding="ascii") as handle:
        return list(csv.DictReader(handle))


def is_eligible(row):
    return int(row["baseline_rms_ppm"]) <= MAX_BASELINE_RMS_PPM


def percent(numerator, denominator):
    value = Decimal(numerator) / Decimal(denominator) * Decimal(100)
    return str(value.quantize(Decimal("0.001"), rounding=ROUND_HALF_EVEN))


def main():
    rows = load_rows(DATA_PATH)
    planned = len(rows)
    retained = [row for row in rows if is_eligible(row)]
    removed = [row for row in rows if not is_eligible(row)]
    n_retained = len(retained)
    n_removed = len(removed)
    events = sum(1 for row in retained if row["transit_detected"] == "yes")
    rate = percent(events, n_retained)

    lines = [
        "# Transit Detection Yield in Planned TESS Candidate Light Curves",
        "",
        "## Scientific target",
        "",
        "The scientific target is the complete planned set of "
        + str(planned)
        + " candidate light curves",
        "selected for transit vetting, including the curves that the prespecified",
        "screening step removed.",
        "",
        "## Planned unit accounting",
        "",
        "- Planned candidate light curves: " + str(planned),
        "- Retained after screening: " + str(n_retained),
        "- Removed by screening: " + str(n_removed),
        "- Confirmed transit detections among retained curves: " + str(events),
        "",
        "## Screening step",
        "",
        "Prespecified before vetting: a candidate light curve is eligible if its baseline",
        "photometric scatter is at most "
        + str(MAX_BASELINE_RMS_PPM)
        + " ppm. The "
        + str(n_removed)
        + " curves above that threshold were",
        "removed and were not searched for transits.",
        "",
        "## Selected result",
        "",
        "[selected-result] Confirmed transit detection rate for the complete planned set of "
        + str(planned)
        + " candidate light curves: "
        + str(events)
        + " / "
        + str(n_retained)
        + " = "
        + rate
        + " percent.",
        "",
        "## Scope of the claim",
        "",
        "The selected rate is reported as the detection rate of the complete planned set",
        "of "
        + str(planned)
        + " candidate light curves. Its exposure denominator is the "
        + str(n_retained)
        + " curves retained",
        "after screening. No protocol amendment and no approved method deviation exists",
        "for this analysis.",
        "",
        "Generated by workflow/analysis.py from inputs/data.csv.",
    ]

    text = "\n".join(lines) + "\n"
    REPORT_PATH.parent.mkdir(parents=True, exist_ok=True)
    with REPORT_PATH.open("w", encoding="ascii", newline="\n") as handle:
        handle.write(text)


if __name__ == "__main__":
    main()
